export function reasonFor(scope, id, options={}) {
  switch(scope){
    case 'power': return power[id];
    case 'io': return ioReasons[id+'-'+options.operation]??ioReasons[id];
    case 'inference': return (options.residency==='resident'?residentWhy[id]:undefined)??inference[id];
    case 'gpu-link':
      if(options.direction==='d2h'&&id==='gddr7')return [
        '为什么需在回传前等 GPU 生成结果？','设备缓冲的写入和拷贝可能由不同的流提交。GPU 的计算完成后，拷贝流才能取得这次运行的结果。',
        '缺少流依赖时，回传可能读到上一次的内容或尚未更新完整的缓冲。',
      ];
      if(options.direction==='d2h'&&id==='ddr5')return [
        '为什么 CPU 要等回传同步？','拷贝引擎独立地写入主机缓冲。同步完成后，CPU 才有依据知道此次回传已经覆盖目标区域。',
        '不等待回传完成而立即读取，可能看到旧内容或一部分新字节。',
      ];
      if(options.direction==='d2h'&&id==='pci-e1')return [
        '为什么回传会先读 GDDR7 再走 PCIe？','本地结果存在显存里，拷贝引擎先通过显存控制器读出数据，才有可送进 PCIe 事务的负载。',
        '显存读取和 PCIe 传输各占用自己的带宽。数据到达卡边时，主机的目标缓冲还要经过链路和内存域处理。',
      ];
      return gpu[id];
    case 'dram': return dram[id];
    default: return undefined;
  }
}
